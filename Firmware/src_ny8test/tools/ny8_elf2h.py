#!/usr/bin/env python3
"""Convert an NY8 ELF (Nyquest LLVM toolchain) into a C header for src_ny8test.

Reads the allocated ROM sections directly from the ELF, so words not covered by any
section stay unprogrammed (llvm-objcopy -O binary would fill gaps with 0x0000 = NOP).
Words are written in the toolchain's encoding; src_ny8test applies NY8_IMAGE_XOR
before programming (see NY8_ISA.md).

usage: ny8_elf2h.py input.elf ny8_image.h [--rom-words 512]
"""
import argparse
import struct
import sys

SHF_ALLOC = 0x2
SHT_PROGBITS = 1


def rom_words(path, rom_words):
    d = open(path, 'rb').read()
    if d[:4] != b'\x7fELF' or d[4] != 1 or d[5] != 1:
        sys.exit('not a 32-bit little-endian ELF')
    shoff, = struct.unpack_from('<I', d, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', d, 0x2E)
    secs = [struct.unpack_from('<IIIIIIIIII', d, shoff + i * shentsize) for i in range(shnum)]
    strsec = secs[shstrndx]

    def name(off):
        return d[strsec[4] + off:].split(b'\0', 1)[0].decode()

    words = [None] * rom_words
    for s in secs:
        sh_name, sh_type, sh_flags, sh_addr, sh_offset, sh_size = s[:6]
        if sh_type != SHT_PROGBITS or not (sh_flags & SHF_ALLOC) or sh_size == 0:
            continue
        if sh_addr >= 0x400000:          # RAM sections
            continue
        if sh_addr & 1 or sh_size & 1:
            sys.exit(f'section {name(sh_name)} not word aligned')
        raw = d[sh_offset:sh_offset + sh_size]
        for i in range(0, sh_size, 2):
            a = (sh_addr + i) // 2
            if a >= rom_words:
                sys.exit(f'section {name(sh_name)} exceeds ROM ({a:#x})')
            if words[a] is not None:
                sys.exit(f'overlap at word {a:#x}')
            words[a] = struct.unpack_from('<H', raw, i)[0] & 0x3FFF
        print(f'  {name(sh_name):12s} words {sh_addr // 2:03X}..{(sh_addr + sh_size) // 2 - 1:03X}')
    return words


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('elf')
    ap.add_argument('header')
    ap.add_argument('--rom-words', type=int, default=512)
    a = ap.parse_args()
    w = rom_words(a.elf, a.rom_words)
    used = [i for i, x in enumerate(w) if x is not None]
    if not used:
        sys.exit('no ROM content')
    for r in (0x00E, 0x00F, a.rom_words - 2, a.rom_words - 1):
        if w[r] is not None:
            print(f'warning: word {r:#05x} is reserved (rolling code / reserved area)')
    with open(a.header, 'w') as f:
        f.write(f'// generated by ny8_elf2h.py from {a.elf}\n')
        f.write('// {address, word} pairs in toolchain encoding (NY8_IMAGE_XOR applied when programming)\n')
        f.write('#include <stdint.h>\n\n')
        f.write('static const uint16_t ny8_image[][2] = {\n')
        for i in used:
            f.write(f'\t{{0x{i:03X}, 0x{w[i]:04X}}},\n')
        f.write('};\n')
        f.write(f'#define NY8_IMAGE_LEN {len(used)}\n')
    print(f'{len(used)} words -> {a.header}')


if __name__ == '__main__':
    main()
